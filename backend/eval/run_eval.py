"""Run the deterministic evaluation set and print a report.   python eval/run_eval.py [--md docs/EVAL_RESULTS.md]"""
from __future__ import annotations

import argparse
import sys
import time
import traceback
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from cases import CASES  # noqa: E402


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--md", help="also write a Markdown report to this path")
    args = ap.parse_args()
    rows, failed = [], 0
    for cid, desc, fn in CASES:
        t = time.time()
        try:
            res = fn()
        except Exception as e:  # noqa: BLE001
            res = {"passed": False, "checks": [("raised an exception", False)], "excerpt": traceback.format_exc(limit=3)}
            print(f"[{cid}] EXCEPTION {e}")
        dt = time.time() - t
        failed += 0 if res["passed"] else 1
        print(f"[{cid}] {'PASS' if res['passed'] else 'FAIL'}  {desc}  ({dt:.1f}s)")
        for name, ok in res["checks"]:
            print(f"      {'ok ' if ok else 'XX '} {name}")
        print(f"      -> {res['excerpt'][:400]}")
        rows.append((cid, desc, res, dt))
    print(f"\n{len(CASES) - failed}/{len(CASES)} cases passed")
    if args.md:
        lines = ["# Deterministic evaluation results", "",
                 "Generated by `python eval/run_eval.py --md ...`. These cases call the same tools the chatbot uses and verify",
                 "them against independent recomputation or invariants (no LLM involved).", "",
                 "| Case | Description | Result |", "|---|---|---|"]
        for cid, desc, res, _ in rows:
            lines.append(f"| {cid} | {desc} | {'PASS' if res['passed'] else 'FAIL'} |")
        lines.append("")
        for cid, desc, res, dt in rows:
            lines += [f"## {cid} - {desc}", "", f"Result: **{'PASS' if res['passed'] else 'FAIL'}** ({dt:.1f}s)", ""]
            lines += [f"- {'[x]' if ok else '[ ]'} {name}" for name, ok in res["checks"]]
            lines += ["", "Observed output:", "", "```", res["excerpt"][:900], "```", ""]
        Path(args.md).parent.mkdir(parents=True, exist_ok=True)
        Path(args.md).write_text("\n".join(lines), encoding="utf-8")
        print("wrote", args.md)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
